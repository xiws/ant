type rcView struct {
	work string
}

func (v rcView) Settings() config.Settings        { return config.Settings{} }
func (v rcView) Models() []config.ModelSpec       { return nil }
func (v rcView) Providers() []config.ProviderSpec { return nil }
func (v rcView) Origin(string) (config.Origin, bool) {
	return "", false
}
func (v rcView) Warnings() []string { return nil }
func (v rcView) WorkDir() string    { return v.work }
func (v rcView) HomeDir() string    { return filepath.Join(v.work, ".home") }

func writeRC(t *testing.T, root, rel, body string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func newRCWorkspace(t *testing.T) (string, Index) {
	t.Helper()
	root := t.TempDir()
	writeRC(t, root, "go.mod", "module example.com/demo\n\ngo 1.26\n")
	writeRC(t, root, "pkg/a.go", `package pkg

// A doc
func A() {
	var t T
	helper()
	t.M()
	B()
}

func helper() {}

func B() { C() }

func C() {}

type T struct{}

func (t T) M() {}

func (t *T) N() {}
`)
	writeRC(t, root, "pkg/a_test.go", "package pkg\n\nfunc TestOnly() {}\n")
	writeRC(t, root, "cmd/main.go", "package main\n\nimport \"example.com/demo/pkg\"\n\nfunc main() { pkg.A() }\n")
	writeRC(t, root, "gen.go", "// Code generated by tool. DO NOT EDIT.\npackage demo\n\nfunc Generated() {}\n")
	writeRC(t, root, "vendor/x.go", "package vendorx\n\nfunc Vendored() {}\n")
	return root, NewIndex(rcView{work: root})
}

func TestResolveForms(t *testing.T) {
	root, idx := newRCWorkspace(t)
	ctx := context.Background()

	cases := []struct {
		target string
		file   string
		name   string
	}{
		{"A", "pkg/a.go", "A"},
		{"pkg.A", "pkg/a.go", "A"},
		{"pkg/a.go#A", "pkg/a.go", "A"},
		{"pkg/a.go:5", "pkg/a.go", "A"},
		{"cmd/main.go:5", "cmd/main.go", "main"},
	}
	for _, tc := range cases {
		sym, err := idx.Resolve(ctx, tc.target)
		if err != nil {
			t.Fatalf("Resolve(%q): %v", tc.target, err)
		}
		if sym.File != tc.file || sym.Name != tc.name {
			t.Fatalf("Resolve(%q) = %+v", tc.target, sym)
		}
	}
	if _, err := idx.Resolve(ctx, "pkg/a.go:999"); err == nil {
		t.Fatal("超出函数范围的行号应报错")
	}
	if _, err := idx.Resolve(ctx, "Nope"); err == nil || model.CodeOf(err) != "not_found" {
		t.Fatalf("not found err = %v", err)
	}
	if _, err := idx.Resolve(ctx, "Generated"); err == nil {
		t.Fatal("生成文件应被跳过")
	}
	if sym, err := idx.Resolve(ctx, "TestOnly"); err != nil {
		t.Fatalf("测试符号应能解析: %v", err)
	} else if !strings.HasSuffix(sym.File, "_test.go") {
		t.Fatalf("test sym = %+v", sym)
	}
	_ = root
}

func TestResolveAmbiguous(t *testing.T) {
	root := t.TempDir()
	writeRC(t, root, "go.mod", "module example.com/demo\n\ngo 1.26\n")
	writeRC(t, root, "a/a.go", "package a\n\nfunc Dup() {}\n")
	writeRC(t, root, "b/b.go", "package b\n\nfunc Dup() {}\n")
	idx := NewIndex(rcView{work: root})
	_, err := idx.Resolve(context.Background(), "Dup")
	if err == nil || model.CodeOf(err) != "ambiguous_symbol" {
		t.Fatalf("err = %v", err)
	}
}

func TestClosureBFSDepthAndMethods(t *testing.T) {
	root, idx := newRCWorkspace(t)
	ctx := context.Background()
	rootSym, err := idx.Resolve(ctx, "A")
	if err != nil {
		t.Fatal(err)
	}
	snippets, err := idx.Closure(ctx, rootSym, Options{Depth: 1, MaxSymbols: 20})
	if err != nil {
		t.Fatal(err)
	}
	joined := joinSnippets(snippets)
	for _, want := range []string{"func A()", "func helper()", "func (t T) M()", "func B()"} {
		if !strings.Contains(joined, want) {
			t.Errorf("depth=1 缺少 %q:\n%s", want, joined)
		}
	}
	if strings.Contains(joined, "func C()") {
		t.Errorf("depth=1 不应包含 C:\n%s", joined)
	}

	snippets, err = idx.Closure(ctx, rootSym, Options{Depth: 3, MaxSymbols: 20})
	if err != nil {
		t.Fatal(err)
	}
	joined = joinSnippets(snippets)
	if !strings.Contains(joined, "func C()") {
		t.Fatalf("depth=3 应包含 C:\n%s", joined)
	}
	if strings.Contains(joined, "TestOnly") {
		t.Fatalf("默认不应包含测试文件:\n%s", joined)
	}
	if !strings.Contains(joined, "// A doc") {
		t.Fatalf("应保留紧邻文档注释:\n%s", joined)
	}
	_ = root

	// maxSymbols 截断应记录 omitted。
	snippets, err = idx.Closure(ctx, rootSym, Options{Depth: 3, MaxSymbols: 2})
	if err != nil {
		t.Fatal(err)
	}
	if len(snippets) > 2 {
		t.Fatalf("maxSymbols 未生效: %d", len(snippets))
	}
	oi, ok := idx.(interface{ Omitted() []string })
	if !ok || len(oi.Omitted()) == 0 {
		t.Fatalf("应记录被省略的符号")
	}
}

func TestClosureMethodViaImport(t *testing.T) {
	root, idx := newRCWorkspace(t)
	sym, err := idx.Resolve(context.Background(), "main")
	if err != nil {
		t.Fatal(err)
	}
	snippets, err := idx.Closure(context.Background(), sym, Options{Depth: 2, MaxSymbols: 20})
	if err != nil {
		t.Fatal(err)
	}
	joined := joinSnippets(snippets)
	if !strings.Contains(joined, "func A()") {
		t.Fatalf("跨包调用未解析:\n%s", joined)
	}
	if strings.Contains(joined, "func Vendored()") {
		t.Fatalf("第三方/vendor 不应展开:\n%s", joined)
	}
	_ = root
}

func TestInvalidateRebuilds(t *testing.T) {
	root, idx := newRCWorkspace(t)
	ctx := context.Background()
	if _, err := idx.Resolve(ctx, "D"); err == nil {
		t.Fatal("D 尚不存在")
	}
	writeRC(t, root, "pkg/d.go", "package pkg\n\nfunc D() {}\n")
	idx.Invalidate([]string{"pkg/d.go"})
	if _, err := idx.Resolve(ctx, "D"); err != nil {
		t.Fatalf("Invalidate 后应看到新符号: %v", err)
	}
}

func joinSnippets(snippets []Snippet) string {
	var b strings.Builder
	for _, s := range snippets {
		b.WriteString(s.Code)
		b.WriteString("\n")
	}
	return b.String()
}
